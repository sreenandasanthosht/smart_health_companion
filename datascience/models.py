"""
datascience app models.

Phase 5 (task 4.1) needs a synthetic cohort to train and evaluate models
on, since the app's own real usage data is far too small and far too new
to learn anything defensible from. SyntheticPatient is the marker that
separates "fake patient used only for training/evaluation" from a real
person who has signed up -- every place that touches training data filters
on this table, and nothing that reads it is ever shown to a real user.

The tendency fields (sleep_tendency, adherence_tendency, activity_tendency)
are the GROUND TRUTH used to generate that patient's fake day-to-day logs.
They are deliberately NOT included as a model feature -- a real patient has
no such field, so a model that could see it would be learning something it
could never use in production. Features are computed only from the noisy,
observable logs (VitalRecord / MedicationDose / LifestyleLog), the same way
they would be for a real patient. See datascience/features.py.
"""
from django.conf import settings
from django.db import models


class SyntheticPatient(models.Model):
    """One synthetic patient generated by `generate_cohort`, plus the
    hidden per-patient tendencies used to shape their fake history."""

    user = models.OneToOneField(settings.AUTH_USER_MODEL, on_delete=models.CASCADE,
                                 related_name='synthetic_profile')
    age = models.PositiveIntegerField()
    sex = models.CharField(max_length=1)
    chronic_hypertension = models.BooleanField(default=False)
    chronic_diabetes = models.BooleanField(default=False)

    # Ground truth, 0.0-1.0, higher = healthier behaviour on that axis.
    # Used only to GENERATE the fake logs and to LABEL the training data --
    # never fed to a model as an input feature. One tendency per
    # recommendation candidate in datascience/recommend.py.
    sleep_tendency = models.FloatField()
    adherence_tendency = models.FloatField()
    activity_tendency = models.FloatField()
    hydration_tendency = models.FloatField()
    engagement_tendency = models.FloatField(help_text='How consistently this patient logs data at all.')

    seed = models.PositiveIntegerField(help_text='RNG seed used for this patient, for reproducibility.')
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['id']

    def __str__(self):
        return f"Synthetic patient #{self.pk} ({self.user.email})"
